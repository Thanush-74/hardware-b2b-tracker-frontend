/**
 * Helper mapping to get an icon by screen slug
 */
export const getScreenIcon = (slug, props = {}) => {
  const safeProps = { ...props };
  if (typeof safeProps.fontSize === 'number') {
    safeProps.sx = { fontSize: safeProps.fontSize, ...(safeProps.sx || {}) };
    delete safeProps.fontSize;
  }

  switch (slug) {
    case 'dashboard':
      return <DashboardIcon {...safeProps} />;
    case 'staff':
      return <StaffIcon {...safeProps} />;
    case 'products':
      return <ProductsIcon {...safeProps} />;
    case 'inventory':
      return <InventoryIcon {...safeProps} />;
    case 'orders':
      return <OrdersIcon {...safeProps} />;
    case 'deliveries':
      return <DeliveriesIcon {...safeProps} />;
    case 'cart':
      return <CartIcon {...safeProps} />;
    case 'production':
      return <ProductionIcon {...safeProps} />;
    case 'returns':
      return <ReturnsIcon {...safeProps} />;
    case 'manufacturing':
      return <ManufacturingIcon {...safeProps} />;
    case 'expenses':
      return <ExpensesIcon {...safeProps} />;
    case 'inspection':
      return <InspectionIcon {...safeProps} />;
    case 'roles':
      return <RolesIcon {...safeProps} />;
    default:
      return <DashboardIcon {...safeProps} />;
  }
};
